export function getCard(id: string): CreditCardProduct | undefined {
  return CARDS.find((c) => c.id === id);
}

export function searchCards(query: string): CreditCardProduct[] {
  const q = query.trim().toLowerCase();
  if (!q) return CARDS;
  return CARDS.filter(
    (c) => c.name.toLowerCase().includes(q) || c.issuerId.toLowerCase().includes(q)
  );
}
